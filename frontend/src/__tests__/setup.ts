// Gaps de jsdom que necesitan varios specs (vistas montan el layout real,
// que usa useTheme → matchMedia). Centralizado aquí en vez de repetido.
if (!window.matchMedia) {
  window.matchMedia = ((query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  })) as unknown as typeof window.matchMedia;
}
